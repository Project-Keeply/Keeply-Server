-- GroupMember의 MySQL IF(...) VIRTUAL 문법을 H2 테스트에서만 CASE로 대체한다.
-- 운영 엔티티/마이그레이션 검증을 대신하지 않는다.
CREATE TABLE IF NOT EXISTS group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    joined_at TIMESTAMP(6) NOT NULL,
    deleted_at TIMESTAMP(6),
    deleted_flag TINYINT GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN 0 ELSE NULL END),
    role VARCHAR(20) NOT NULL,
    CONSTRAINT uq_group_members_user_id_active UNIQUE (user_id, deleted_flag),
    CONSTRAINT uq_group_members_group_user UNIQUE (group_id, user_id),
    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (group_id) REFERENCES store_groups(id)
);
DELETE FROM group_members;
